#include <iostream>
#include <iomanip>

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Константи програми (Лабораторна робота 2.4, Варіант 3)
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

const double X_START = -4.0;   // Початок інтервалу табулювання (Таблиця 24)
const double X_END   =  4.0;   // Кінець інтервалу табулювання
const double X_STEP  =  0.5;   // Крок табулювання h
const int    I_START =  2;     // Нижня межа суми
const int    I_END   =  4;     // Верхня межа суми

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Відкрита підпрограма (inline) для піднесення до квадрату
// (Методична вказівка: невеликі підпрограми ~5 операторів робити відкритими)
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
inline double square(double dVal)
{
    return dVal * dVal;
}

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Частина 1: Закрита підпрограма обчислення функції y(x) за Варіантом 3
// Реалізує єдину концепцію (лише обчислення без глобальних змінних та виводу)
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
double calculateFunction(double dX)
{
    double dY = 0.0;

    if (dX < 0.0)
    {
        // Гілка 1 (x < 0): сума від i = 2 до 4 виразу (i + x) * (i - x^2)
        double dSum = 0.0;
        for (int i = I_START; i <= I_END; i++)
        {
            dSum += (i + dX) * (i - square(dX));
        }
        dY = dSum;
    }
    else
    {
        // Гілка 2 (x >= 0): x^2 + x / 2
        dY = square(dX) + (dX / 2.0);
    }

    return dY;
}

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Частина 2: Головна функція main (табулювання функції на відрізку [-4, 4])
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
int main()
{
    std::cout << "~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n";
    std::cout << "       LABORATORY WORK 2.4: CLOSED SUBROUTINES (VARIANT 3)\n";
    std::cout << "~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n\n";

    std::cout << "Tabulation of y(x) on [" << X_START << "; " << X_END
              << "] with step h = " << X_STEP << ":\n\n";

    std::cout << "------------------------------------------\n";
    std::cout << "| " << std::right << std::setw(14) << "Argument x"
              << " | " << std::right << std::setw(21) << "Function y(x)"
              << " |\n";
    std::cout << "------------------------------------------\n";

    std::cout << std::fixed;
    for (double dX = X_START; dX <= X_END + 1e-9; dX += X_STEP)
    {
        double dResultY = calculateFunction(dX);

        std::cout << "| " << std::right << std::setw(14) << std::setprecision(1) << dX
                  << " | " << std::right << std::setw(21) << std::setprecision(3) << dResultY
                  << " |\n";
    }

    std::cout << "------------------------------------------\n\n";
    std::cout << "~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n";
    std::cout << "              Laboratory work 2.4 completed successfully.\n";
    std::cout << "~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n";

    return 0;
}
